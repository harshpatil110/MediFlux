"""MediFlux Unified Full-Stack Launcher (Task 28).

Orchestrates FastAPI backend, Vite web frontend, and Electron/Tauri desktop wrapper.
Supports --check-only flag for CI/pytest verification without spawning daemon processes.
"""

from __future__ import annotations

import argparse
import os
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import Literal

ROOT_DIR = Path(__file__).resolve().parent.parent
BACKEND_DIR = ROOT_DIR / "backend"
FRONTEND_DIR = ROOT_DIR / "frontend"
DESKTOP_DIR = ROOT_DIR / "desktop"
MOBILE_DIR = ROOT_DIR / "mobile"


def detect_lan_ip() -> str:
    """Detect primary LAN IPv4 address using UDP socket probe."""
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        # Non-routable external address to detect default routing interface
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
    except Exception:
        ip = "127.0.0.1"
    finally:
        s.close()
    return ip


def sync_mobile_env(lan_ip: str, port: int = 8000) -> None:
    """Synchronize detected LAN IP into mobile/.env.local for zero-config phone pairing."""
    MOBILE_DIR.mkdir(parents=True, exist_ok=True)
    env_local = MOBILE_DIR / ".env.local"
    content = (
        f"# Auto-generated by scripts/start_all.py --lan\n"
        f"EXPO_PUBLIC_LAN_API_URL=http://{lan_ip}:{port}\n"
        f"EXPO_PUBLIC_API_URL=http://{lan_ip}:{port}\n"
    )
    env_local.write_text(content, encoding="utf-8")


def verify_environment(verbose: bool = True) -> bool:
    """Verify all required files and artifacts exist for desktop and web packaging."""
    critical_paths = [
        BACKEND_DIR / "app" / "main.py",
        BACKEND_DIR / "app" / "core" / "config.py",
        FRONTEND_DIR / "vite.config.ts",
        FRONTEND_DIR / "src" / "App.tsx",
        FRONTEND_DIR / "src" / "config" / "env.ts",
        FRONTEND_DIR / "src" / "components" / "layout" / "BackendSettingsModal.tsx",
        DESKTOP_DIR / "package.json",
        DESKTOP_DIR / "main.cjs",
        DESKTOP_DIR / "preload.cjs",
        DESKTOP_DIR / "icons" / "icon.ico",
        DESKTOP_DIR / "icons" / "icon.png",
        DESKTOP_DIR / "src-tauri" / "tauri.conf.json",
        DESKTOP_DIR / "src-tauri" / "Cargo.toml",
    ]

    missing = [str(p.relative_to(ROOT_DIR)) for p in critical_paths if not p.exists()]
    if missing:
        if verbose:
            print(f"[FAIL] Missing critical paths: {missing}", file=sys.stderr)
        return False

    if verbose:
        print("[OK] All critical backend, frontend, Tauri, and Electron files verified.")
        print(f"     Root Directory: {ROOT_DIR}")
        print(f"     Desktop Entry:  {DESKTOP_DIR / 'main.cjs'}")
        print(f"     Tauri Conf:     {DESKTOP_DIR / 'src-tauri' / 'tauri.conf.json'}")

    return True


def run_check_only(lan: bool = False, port: int = 8000) -> int:
    """Execute dry-run environment validation and exit cleanly."""
    print("==================================================")
    print("  MediFlux Desktop & Full-Stack Preflight Check   ")
    print("==================================================")
    is_valid = verify_environment(verbose=True)
    if lan:
        lan_ip = detect_lan_ip()
        sync_mobile_env(lan_ip, port=port)
        print("\n======================================================================")
        print(f"  MediFlux Network Endpoints (LAN Mode: host 0.0.0.0:{port})")
        print("======================================================================")
        print(f"  Web / Local URL:             http://localhost:{port}")
        print(f"  Android Emulator URL:        http://10.0.2.2:{port}")
        print(f"  Physical Phone / LAN URL:    http://{lan_ip}:{port}")
        print("======================================================================")
        print(f"  ✓ Synchronized mobile/.env.local with EXPO_PUBLIC_LAN_API_URL=http://{lan_ip}:{port}")

    if is_valid:
        print("\n[SUCCESS] MediFlux Desktop & Full-Stack launcher check passed cleanly.")
        return 0
    print("\n[FAILURE] Preflight check failed.")
    return 1


def launch(mode: Literal["desktop", "web", "both"], port: int = 8000, lan: bool = False) -> int:
    """Launch backend along with selected client interface."""
    if not verify_environment(verbose=True):
        return 1

    venv_python = BACKEND_DIR / "venv" / "Scripts" / "python.exe"
    python_exec = str(venv_python) if venv_python.exists() else sys.executable

    npm_cmd = "npm.cmd" if os.name == "nt" else "npm"

    processes: list[subprocess.Popen] = []

    try:
        host = "0.0.0.0" if lan else "127.0.0.1"
        backend_args = [python_exec, "-m", "uvicorn", "app.main:app", "--reload", "--host", host, "--port", str(port)]
        
        if lan:
            lan_ip = detect_lan_ip()
            sync_mobile_env(lan_ip, port=port)
            print("======================================================================")
            print(f"  MediFlux Network Endpoints (LAN Mode Active: host 0.0.0.0:{port})")
            print("======================================================================")
            print(f"  Web / Local URL:             http://localhost:{port}")
            print(f"  Android Emulator URL:        http://10.0.2.2:{port}")
            print(f"  Physical Phone / LAN URL:    http://{lan_ip}:{port}")
            print("======================================================================")
            print(f"  ✓ Synchronized mobile/.env.local (EXPO_PUBLIC_LAN_API_URL=http://{lan_ip}:{port})")
            print(f"\n[Backend] Starting FastAPI on host 0.0.0.0:{port} (LAN accessible)...")
        else:
            print(f"[Backend] Starting FastAPI on http://localhost:{port} ...")

        backend_proc = subprocess.Popen(
            backend_args,
            cwd=str(BACKEND_DIR),
        )
        processes.append(backend_proc)

        # Allow backend to bind socket
        time.sleep(2)

        if mode in ("web", "both"):
            print("[Frontend] Starting Vite dev server on http://localhost:5173 ...")
            web_proc = subprocess.Popen(
                [npm_cmd, "run", "dev"],
                cwd=str(FRONTEND_DIR),
            )
            processes.append(web_proc)

        if mode in ("desktop", "both"):
            print("[Desktop] Launching MediFlux Desktop shell (Electron) ...")
            desktop_proc = subprocess.Popen(
                [npm_cmd, "run", "desktop:dev"],
                cwd=str(DESKTOP_DIR),
            )
            processes.append(desktop_proc)

        print("\nAll MediFlux processes running. Press Ctrl+C to terminate.")
        while True:
            time.sleep(1)
            for p in processes:
                if p.poll() is not None:
                    print(f"Process {p.args} exited with code {p.returncode}")
                    return p.returncode

    except KeyboardInterrupt:
        print("\nShutting down all MediFlux processes gracefully...")
    finally:
        for p in processes:
            if p.poll() is None:
                p.terminate()
                try:
                    p.wait(timeout=3)
                except subprocess.TimeoutExpired:
                    p.kill()

    return 0


def main() -> None:
    parser = argparse.ArgumentParser(description="MediFlux Full-Stack & Desktop Application Launcher")
    parser.add_argument(
        "--check-only",
        action="store_true",
        help="Run environment and desktop packaging preflight checks without launching processes.",
    )
    parser.add_argument(
        "--lan",
        action="store_true",
        help="Bind FastAPI to 0.0.0.0 and detect LAN IP for mobile phone / emulator access.",
    )
    parser.add_argument(
        "--mode",
        choices=["desktop", "web", "both"],
        default="both",
        help="Launch target: desktop shell, web browser, or both (default: both).",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=8000,
        help="FastAPI backend port (default: 8000).",
    )

    args = parser.parse_args()

    if args.check_only:
        sys.exit(run_check_only(lan=args.lan, port=args.port))

    sys.exit(launch(mode=args.mode, port=args.port, lan=args.lan))


if __name__ == "__main__":
    main()

